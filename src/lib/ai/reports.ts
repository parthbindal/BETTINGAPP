/**
 * Research reports: structured output from the model when configured, or a
 * deterministic builder from the same retrieved data otherwise. Both paths
 * produce the identical schema so the UI has one renderer.
 */
import Anthropic from "@anthropic-ai/sdk";
import { z } from "zod";
import { zodOutputFormat } from "@anthropic-ai/sdk/helpers/zod";
import { getAnthropic, AI_MODEL } from "@/lib/ai/client";
import { REPORT_SYSTEM_PROMPT } from "@/lib/ai/prompts";
import { runTool, type ToolContext } from "@/lib/ai/tools";
import { estimateCostUsd } from "@/lib/ai/pricing";
import { db } from "@/lib/db";
import { logError } from "@/lib/ops";
import type { Prisma } from "@/generated/prisma/client";
import { pct, cents, compact } from "@/lib/format";

export const ReportSchema = z.object({
  title: z.string(),
  executiveSummary: z.string(),
  keyStatistics: z.array(z.object({ label: z.string(), value: z.string(), source: z.string() })),
  historicalComparison: z.array(z.string()),
  probabilityAnalysis: z.object({
    marketProbability: z.number().nullable(),
    modelEstimate: z.number().nullable(),
    differenceDescription: z.string(),
    interpretation: z.string(),
  }),
  supportingEvidence: z.array(z.string()),
  counterarguments: z.array(z.string()),
  potentialCatalysts: z.array(z.string()),
  riskFactors: z.array(z.string()),
  dataQuality: z.object({ rating: z.enum(["low", "medium", "high"]), notes: z.array(z.string()) }),
  confidence: z.object({ level: z.enum(["low", "medium", "high"]), rationale: z.string() }),
  sources: z.array(z.object({ name: z.string(), freshness: z.string(), fetchedAt: z.string() })),
  disclaimer: z.string(),
});
export type Report = z.infer<typeof ReportSchema>;

export interface ReportRequest {
  userId: string;
  ctx: ToolContext;
  subjectKind: "market" | "player";
  subjectRef: string;
  stat?: string;
  line?: number;
}

const DISCLAIMER = "Educational analysis only. Not financial advice. Probabilities and model estimates are uncertain; historical performance does not guarantee future results.";

async function gather(req: ReportRequest) {
  if (req.subjectKind === "market") {
    const market = await runTool("get_market", { ticker: req.subjectRef }, req.ctx);
    const history = await runTool("get_market_history", { ticker: req.subjectRef, days: 30 }, req.ctx);
    return { kind: "market" as const, market, history };
  }
  const player = await runTool("get_player", { playerId: req.subjectRef }, req.ctx);
  const projection = req.stat && req.line !== undefined ? await runTool("analyze_projection", { playerId: req.subjectRef, stat: req.stat, line: req.line }, req.ctx) : null;
  return { kind: "player" as const, player, projection };
}

function buildDeterministic(data: Awaited<ReturnType<typeof gather>>): Report {
  if (data.kind === "market") {
    const r = data.market as Record<string, unknown>;
    if ("error" in r) throw new Error("Market not found");
    const m = r.market as Record<string, unknown> & { provenance: { source: string; freshness: string; fetchedAt: string } };
    const model = r.model as Record<string, unknown>;
    const mv = (r.movement as Record<string, number> | null) ?? null;
    const diff = model.diffPts as number | null;
    return {
      title: `${m.title}${m.yesSubTitle ? ` — ${m.yesSubTitle}` : ""}`,
      executiveSummary: `The market implies a ${pct(m.impliedProbability as number, 1)} probability (bid ${cents(m.yesBid as number)} / ask ${cents(m.yesAsk as number)}) with ${compact(m.volume24h as number)} contracts traded in the last 24 hours. The EDGEWISE heuristic model estimates ${pct(model.estimate as number, 1)} (${model.confidence as string} confidence), a ${diff !== null ? (diff * 100).toFixed(1) : "—"} point difference that is ${model.noteworthy ? "larger than the spread and estimated fees, which makes it worth researching" : "within the spread and fee noise, which suggests the market is pricing this efficiently"}. This report was generated by fixed rules because no AI provider is configured.`,
      keyStatistics: [
        { label: "Implied probability", value: pct(m.impliedProbability as number, 1), source: `${m.provenance.source} (${m.provenance.freshness})` },
        { label: "Bid / Ask", value: `${cents(m.yesBid as number)} / ${cents(m.yesAsk as number)}`, source: m.provenance.source },
        { label: "24h volume", value: compact(m.volume24h as number), source: m.provenance.source },
        { label: "Open interest", value: compact(m.openInterest as number), source: m.provenance.source },
        { label: "Closes", value: String(m.closeTime ?? "—"), source: m.provenance.source },
        { label: "Model estimate", value: pct(model.estimate as number, 1), source: `EDGEWISE ${model.modelVersion as string}` },
      ],
      historicalComparison: mv
        ? [
            `Over the retrieved window the price moved from ${pct(mv.first, 0)} to ${pct(mv.last, 0)} (range ${pct(mv.low, 0)}–${pct(mv.high, 0)}).`,
            `Largest single-period move: ${(mv.biggestMove as unknown as { delta: number }).delta >= 0 ? "+" : ""}${((mv.biggestMove as unknown as { delta: number }).delta * 100).toFixed(0)} points.`,
            `Price volatility (σ of closes): ${(mv.volatility * 100).toFixed(1)} points.`,
          ]
        : ["Insufficient candle history was available for a historical comparison."],
      probabilityAnalysis: {
        marketProbability: (m.impliedProbability as number) ?? null,
        modelEstimate: (model.estimate as number) ?? null,
        differenceDescription: diff !== null ? `${(diff * 100).toFixed(1)} points (model minus market); after approximate fees ${((model.netOfFeesDiff as number) * 100).toFixed(1)} points.` : "No comparison possible.",
        interpretation: (model.explanation as string[]).join(" "),
      },
      supportingEvidence: [`Liquidity: ${compact(m.volume24h as number)} 24h volume and ${compact(m.openInterest as number)} open interest.`, `Resolution rules: ${String(m.rulesPrimary ?? "not provided").slice(0, 300)}`],
      counterarguments: ["The heuristic model has no information about the real-world event; its estimate derives only from price microstructure and a generic calibration prior.", "Late-moving prices often reflect new information that the model cannot see."],
      potentialCatalysts: ["Scheduled data releases or events referenced in the resolution rules.", "News that changes the settlement source's expected reading."],
      riskFactors: (model.caveats as string[]) ?? [],
      dataQuality: { rating: m.provenance.freshness === "live" ? "high" : "medium", notes: [`Quote fetched ${m.provenance.fetchedAt}.`, `${r.candleCount as number} candles over ${r.historyDays as number} days.`] },
      confidence: { level: model.confidence as "low" | "medium" | "high", rationale: "Confidence reflects spread, 24h volume and history depth, not knowledge of the event." },
      sources: [{ name: "Kalshi public market data", freshness: m.provenance.freshness, fetchedAt: m.provenance.fetchedAt }, { name: `EDGEWISE model ${model.modelVersion as string}`, freshness: "estimate", fetchedAt: new Date().toISOString() }],
      disclaimer: DISCLAIMER,
    };
  }
  const p = data.player as Record<string, unknown>;
  if ("error" in p) throw new Error("Player not found");
  const player = p.player as Record<string, unknown>;
  const prov = p.provenance as { source: string; freshness: string; fetchedAt: string };
  const proj = data.projection as Record<string, unknown> | null;
  const a = proj ? (proj.analysis as Record<string, unknown>) : null;
  const est = a ? (a.estimate as Record<string, unknown>) : null;
  const w = a ? (a.windows as Record<string, { mean: number; median: number; stdev: number; overRate: number; n: number }>) : null;
  const isDemo = Boolean(player.isDemo);
  return {
    title: `${player.name} — ${a ? `${proj!.statLabel as string} ${a.line as number}` : "Player profile"}`,
    executiveSummary: `${isDemo ? "DEMO DATA: this player and every statistic below are fictional sample data. " : ""}${player.name} (${player.position}, ${player.team}) has ${p.gamesLogged as number} logged games. ${a && w && est ? `Against a ${proj!.statLabel as string} line of ${a.line as number}, the season mean is ${w.season!.mean.toFixed(1)} (median ${w.season!.median}, σ ${w.season!.stdev.toFixed(1)}) with an over rate of ${pct(w.season!.overRate, 0)}. The blended estimate puts P(over) near ${pct(est.probOver as number, 0)} with ${est.confidence as string} confidence.` : ""} Generated by fixed rules because no AI provider is configured.`,
    keyStatistics: [
      { label: "Games logged", value: String(p.gamesLogged), source: prov.source },
      ...(w ? [{ label: "Season mean / median", value: `${w.season!.mean.toFixed(1)} / ${w.season!.median}`, source: prov.source }, { label: "Last 5 mean", value: w.last5!.mean.toFixed(1), source: prov.source }, { label: "Season over rate", value: pct(w.season!.overRate, 0), source: prov.source }] : []),
      { label: "Injury status", value: String(player.injuryStatus ?? "unknown"), source: prov.source },
    ],
    historicalComparison: w ? [`Last 10: mean ${w.last10!.mean.toFixed(1)}, over rate ${pct(w.last10!.overRate, 0)} (n=${w.last10!.n}).`, `Last 5: mean ${w.last5!.mean.toFixed(1)}, over rate ${pct(w.last5!.overRate, 0)} (n=${w.last5!.n}).`] : ["No projection line supplied."],
    probabilityAnalysis: {
      marketProbability: null,
      modelEstimate: est ? (est.probOver as number) : null,
      differenceDescription: est ? `Blend of parametric ${pct(est.parametricProbOver as number, 0)} and shrunk empirical ${pct(est.empiricalProbOver as number, 0)}; interval ${pct((est.interval as { low: number }).low, 0)}–${pct((est.interval as { high: number }).high, 0)}.` : "n/a",
      interpretation: "A line near the median makes a single game close to a coin flip; the estimate mostly reflects how far the line sits from the player's typical output relative to variance.",
    },
    supportingEvidence: a ? ((a.flags as Array<{ level: string; text: string }>).filter((f) => f.level === "info").map((f) => f.text)) : [],
    counterarguments: ["Game logs may not reflect the next game's role, minutes or matchup.", "Recent form is weighted but regression to the season mean is the base case."],
    potentialCatalysts: ["Lineup or injury changes affecting usage.", "Opponent pace and defensive quality."],
    riskFactors: a ? ((a.flags as Array<{ level: string; text: string }>).filter((f) => f.level === "warning").map((f) => f.text)) : [],
    dataQuality: { rating: isDemo ? "low" : "medium", notes: [isDemo ? "Fictional demo dataset; connect a licensed sports provider for real data." : `Source ${prov.source}.`] },
    confidence: { level: est ? (est.confidence as "low" | "medium" | "high") : "low", rationale: "Driven by sample size, variance and minutes stability." },
    sources: [{ name: isDemo ? "EDGEWISE demo sports dataset (fictional)" : prov.source, freshness: prov.freshness, fetchedAt: prov.fetchedAt }],
    disclaimer: DISCLAIMER,
  };
}

export async function generateReport(req: ReportRequest): Promise<{ id: string; report: Report; mode: "llm" | "rules" }> {
  const data = await gather(req);
  const client = getAnthropic();
  let report: Report;
  let mode: "llm" | "rules" = "rules";
  let model = "rules";

  if (client) {
    try {
      const response = await client.messages.parse({
        model: AI_MODEL,
        max_tokens: 8_000,
        system: REPORT_SYSTEM_PROMPT,
        messages: [{ role: "user", content: `Retrieved data (JSON):\n${JSON.stringify(data)}\n\nWrite the research report. Use only these facts. The disclaimer field must read exactly: "${DISCLAIMER}"` }],
        output_config: { format: zodOutputFormat(ReportSchema), effort: "high" },
      });
      if (response.stop_reason === "refusal" || !response.parsed_output) {
        report = buildDeterministic(data);
      } else {
        report = response.parsed_output;
        mode = "llm";
        model = AI_MODEL;
        const cost = estimateCostUsd(AI_MODEL, response.usage);
        await db.aiUsage.create({ data: { userId: req.userId, kind: "report", model: AI_MODEL, inputTokens: response.usage.input_tokens, outputTokens: response.usage.output_tokens, cacheReadTokens: response.usage.cache_read_input_tokens ?? 0, costUsd: cost } }).catch(() => {});
      }
    } catch (e) {
      if (e instanceof Anthropic.APIError) await logError("ai.report", e, { status: e.status });
      else await logError("ai.report", e);
      report = buildDeterministic(data);
    }
  } else {
    report = buildDeterministic(data);
  }

  const isDemo = report.sources.some((s) => /demo/i.test(s.name) || s.freshness === "demo");
  const row = await db.researchReport.create({
    data: {
      userId: req.userId,
      title: report.title,
      subjectKind: req.subjectKind,
      subjectRef: req.subjectRef,
      content: report as unknown as Prisma.InputJsonValue,
      model,
      modelVersion: data.kind === "market" ? "calib-v0.1" : "proj-v0.1",
      dataQuality: report.dataQuality.rating,
      confidence: report.confidence.level,
      sources: report.sources as unknown as Prisma.InputJsonValue,
      isDemoData: isDemo,
    },
  });
  return { id: row.id, report, mode };
}

/** Counts report generations this month (not surviving rows, so deleting a report does not refund quota). */
export async function countReportsThisMonth(userId: string) {
  const start = new Date();
  start.setDate(1);
  start.setHours(0, 0, 0, 0);
  return db.usageEvent.count({ where: { userId, feature: "report.generate", createdAt: { gte: start } } });
}
